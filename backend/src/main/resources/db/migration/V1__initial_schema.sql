CREATE TABLE import_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL REFERENCES data_source(id),
    file_name TEXT NOT NULL,
    file_path TEXT NOT NULL,
    file_sha256 CHAR(64) NOT NULL,
    generated_at TIMESTAMPTZ,
    status TEXT NOT NULL,
    total_count INT NOT NULL DEFAULT 0,
    inserted_count INT NOT NULL DEFAULT 0,
    updated_count INT NOT NULL DEFAULT 0,
    unchanged_count INT NOT NULL DEFAULT 0,
    failed_count INT NOT NULL DEFAULT 0,
    detail_warning_count INT NOT NULL DEFAULT 0,
    error_message TEXT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ
);

CREATE TABLE camera (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    name_match TEXT NOT NULL,
    longitude NUMERIC(10,7) NOT NULL,
    latitude NUMERIC(10,7) NOT NULL,
    coordinate_system TEXT NOT NULL DEFAULT 'UNKNOWN',
    type_code_raw TEXT NOT NULL,
    manual_protected BOOLEAN NOT NULL DEFAULT false,
    deleted_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT valid_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT valid_latitude CHECK (latitude BETWEEN -90 AND 90)
);
CREATE INDEX camera_name_match_idx ON camera(name_match);
CREATE INDEX camera_coordinates_idx ON camera(longitude, latitude) WHERE deleted_at IS NULL;

CREATE TABLE raw_duomaomao_camera (
    source_record_id TEXT PRIMARY KEY,
    raw_payload JSONB NOT NULL,
    content_hash CHAR(64) NOT NULL,
    last_applied_hash CHAR(64),
    last_seen_batch_id BIGINT NOT NULL REFERENCES import_batch(id),
    detail_status TEXT NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE camera_source_link (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id BIGINT NOT NULL REFERENCES camera(id),
    source_id BIGINT NOT NULL REFERENCES data_source(id),
    source_record_id TEXT NOT NULL,
    linked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source_id, source_record_id)
);
CREATE INDEX camera_source_link_camera_idx ON camera_source_link(camera_id);

CREATE TABLE camera_comment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id BIGINT NOT NULL REFERENCES camera(id),
    nickname TEXT NOT NULL,
    content TEXT NOT NULL,
    raw_time TEXT NOT NULL,
    parsed_time TIMESTAMPTZ,
    fingerprint CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (camera_id, fingerprint)
);
CREATE INDEX camera_comment_page_idx ON camera_comment(camera_id, parsed_time DESC, id DESC);

CREATE TABLE camera_image (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id BIGINT NOT NULL REFERENCES camera(id),
    url TEXT NOT NULL,
    url_hash CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (camera_id, url_hash)
);

CREATE TABLE import_record (
    batch_id BIGINT NOT NULL REFERENCES import_batch(id),
    row_number INT NOT NULL,
    source_record_id TEXT,
    status TEXT NOT NULL,
    error_message TEXT,
    PRIMARY KEY (batch_id, row_number)
);
CREATE INDEX import_record_status_idx ON import_record(batch_id, status);

CREATE TABLE camera_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id BIGINT NOT NULL REFERENCES camera(id),
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    before_value JSONB,
    after_value JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
