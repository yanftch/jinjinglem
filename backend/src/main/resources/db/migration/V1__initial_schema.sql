CREATE TABLE data_source (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    coordinate_system TEXT NOT NULL DEFAULT 'UNKNOWN'
);
