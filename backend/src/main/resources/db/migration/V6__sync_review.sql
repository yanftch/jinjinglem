ALTER TABLE sync_run
    ADD COLUMN review_done INT NOT NULL DEFAULT 0,
    ADD COLUMN mail_status TEXT NOT NULL DEFAULT 'NOT_APPLICABLE',
    ADD COLUMN mail_error TEXT,
    ADD COLUMN mail_sent_at TIMESTAMPTZ;

DROP INDEX sync_run_one_active_per_source;
CREATE UNIQUE INDEX sync_run_one_active_per_source ON sync_run(source_code)
    WHERE status IN ('QUEUED','FETCHING','ARCHIVING','PREPARING_REVIEW','IMPORTING');

CREATE TABLE sync_review_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES sync_run(id),
    batch_id BIGINT NOT NULL REFERENCES import_batch(id),
    row_number INT NOT NULL,
    source_record_id TEXT NOT NULL,
    name TEXT,
    predicted_status TEXT NOT NULL,
    camera_id BIGINT REFERENCES camera(id),
    camera_version BIGINT,
    current_type TEXT,
    proposed_type TEXT,
    new_comment_count INT NOT NULL DEFAULT 0,
    new_image_count INT NOT NULL DEFAULT 0,
    current_snapshot JSONB,
    source_payload JSONB NOT NULL,
    review_note TEXT,
    decision TEXT NOT NULL DEFAULT 'PENDING',
    decision_reason TEXT,
    decided_at TIMESTAMPTZ,
    actual_status TEXT,
    UNIQUE (run_id,row_number),
    UNIQUE (run_id,source_record_id),
    CONSTRAINT sync_review_decision_check CHECK (decision IN ('PENDING','CONFIRMED','REJECTED','APPROVED'))
);
CREATE INDEX sync_review_item_status_idx ON sync_review_item(run_id,predicted_status,decision,row_number);
