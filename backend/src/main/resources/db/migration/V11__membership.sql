CREATE TABLE member_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wechat_openid TEXT NOT NULL UNIQUE,
    trial_started_at TIMESTAMPTZ,
    trial_expires_at TIMESTAMPTZ,
    vip_expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE member_session (
    token_hash CHAR(64) PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES member_account(id),
    device_type TEXT NOT NULL,
    device_id TEXT,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX member_session_account_idx ON member_session(member_id, expires_at);

CREATE TABLE member_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    out_trade_no VARCHAR(32) NOT NULL UNIQUE,
    member_id BIGINT NOT NULL REFERENCES member_account(id),
    plan_code TEXT NOT NULL CHECK (plan_code IN ('MONTH', 'YEAR')),
    product_id TEXT NOT NULL,
    amount_fen INTEGER NOT NULL CHECK (amount_fen > 0),
    status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'PAID', 'REFUNDED', 'CLOSED')),
    wx_order_id TEXT UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    paid_at TIMESTAMPTZ,
    refunded_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX member_order_account_idx ON member_order(member_id, created_at DESC);

CREATE TABLE member_entitlement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES member_account(id),
    source TEXT NOT NULL CHECK (source IN ('PAYMENT', 'ADMIN_ADD', 'ADMIN_SET')),
    order_id BIGINT UNIQUE REFERENCES member_order(id),
    days INTEGER,
    set_expires_at TIMESTAMPTZ,
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    revoked_at TIMESTAMPTZ,
    CHECK ((source = 'ADMIN_SET' AND set_expires_at IS NOT NULL) OR (source <> 'ADMIN_SET' AND days > 0))
);
CREATE INDEX member_entitlement_account_idx ON member_entitlement(member_id, created_at, id);

CREATE TABLE member_payment_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_hash CHAR(64) NOT NULL UNIQUE,
    event_type TEXT NOT NULL,
    out_trade_no TEXT,
    wx_order_id TEXT,
    result TEXT NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE member_app_code (
    code_hash CHAR(64) PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES member_account(id),
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX member_app_code_account_idx ON member_app_code(member_id, expires_at);

CREATE TABLE member_route_request (
    request_id VARCHAR(64) PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES member_account(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE member_admin_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT REFERENCES member_account(id),
    order_id BIGINT REFERENCES member_order(id),
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    reason TEXT,
    outcome TEXT NOT NULL CHECK (outcome IN ('SUCCESS', 'FAILED')),
    before_value JSONB,
    after_value JSONB,
    error_summary TEXT,
    request_id UUID NOT NULL,
    source_ip TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX member_admin_audit_page_idx ON member_admin_audit(created_at DESC, id DESC);
CREATE INDEX member_admin_audit_member_idx ON member_admin_audit(member_id, created_at DESC);
