CREATE TABLE system_membership_gift_config (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    duration TEXT NOT NULL CHECK (duration IN ('30_DAYS', '99_YEARS')),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by TEXT NOT NULL DEFAULT 'system'
);
INSERT INTO system_membership_gift_config(id, duration) VALUES (1, '99_YEARS');

CREATE TABLE system_membership_gift_config_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    duration_before TEXT NOT NULL CHECK (duration_before IN ('30_DAYS', '99_YEARS')),
    duration_after TEXT NOT NULL CHECK (duration_after IN ('30_DAYS', '99_YEARS')),
    actor TEXT NOT NULL,
    source_ip TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Existing accounts receive a fixed 99-year expiry. A latest ADMIN_SET entitlement
-- makes that expiry survive future recalculation caused by old orders/refunds.
INSERT INTO member_entitlement(member_id, source, set_expires_at, reason)
SELECT id, 'ADMIN_SET', now() + interval '99 years', '系统批量统一会员期限为99年'
FROM member_account
ON CONFLICT DO NOTHING;
UPDATE member_account SET vip_expires_at = now() + interval '99 years', updated_at = now();

UPDATE member_entitlement
SET days = 36135, reason = '新用户首次进入小程序赠送99年'
