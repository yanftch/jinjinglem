CREATE TABLE android_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id CHAR(64) NOT NULL UNIQUE,
    device_secret_hash CHAR(64) NOT NULL,
    member_expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX android_user_created_idx ON android_user(created_at DESC, id DESC);

CREATE TABLE android_user_session (
    token_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES android_user(id),
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX android_user_session_user_idx ON android_user_session(user_id, expires_at);

CREATE TABLE android_route_request (
    request_id VARCHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES android_user(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX android_route_request_user_idx ON android_route_request(user_id, expires_at);

CREATE TABLE android_user_admin_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES android_user(id),
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    plan_code TEXT,
    reason TEXT,
    outcome TEXT NOT NULL CHECK (outcome IN ('SUCCESS','FAILED')),
    before_value JSONB,
    after_value JSONB,
    error_summary TEXT,
    request_id UUID NOT NULL,
    source_ip TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX android_user_admin_audit_time_idx ON android_user_admin_audit(created_at DESC, id DESC);
CREATE INDEX android_user_admin_audit_user_idx ON android_user_admin_audit(user_id, created_at DESC);
