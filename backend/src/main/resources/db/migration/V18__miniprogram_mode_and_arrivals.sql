CREATE TABLE miniprogram_mode (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    mode VARCHAR(8) NOT NULL CHECK (mode IN ('LIVE', 'REVIEW')),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by TEXT NOT NULL
);
INSERT INTO miniprogram_mode(id, mode, updated_by) VALUES (1, 'LIVE', 'system');

CREATE TABLE miniprogram_mode_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode_before VARCHAR(8) NOT NULL,
    mode_after VARCHAR(8) NOT NULL,
    actor TEXT NOT NULL,
    source_ip TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX miniprogram_mode_audit_time_idx ON miniprogram_mode_audit(created_at DESC, id DESC);

CREATE TABLE review_arrival (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES member_account(id),
    longitude NUMERIC(10,7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    latitude NUMERIC(10,7) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    accuracy_m NUMERIC(8,2) CHECK (accuracy_m >= 0 AND accuracy_m <= 5000),
    coordinate_system VARCHAR(8) NOT NULL DEFAULT 'GCJ02' CHECK (coordinate_system = 'GCJ02'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX review_arrival_member_time_idx ON review_arrival(member_id, created_at DESC, id DESC);
CREATE INDEX review_arrival_time_idx ON review_arrival(created_at DESC, id DESC);
