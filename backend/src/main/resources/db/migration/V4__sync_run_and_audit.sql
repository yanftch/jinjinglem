CREATE TABLE sync_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code TEXT NOT NULL REFERENCES data_source(code),
    trigger_type TEXT NOT NULL,
    status TEXT NOT NULL,
    phase_message TEXT,
    fetch_done INT NOT NULL DEFAULT 0,
    fetch_total INT NOT NULL DEFAULT 0,
    detail_failures INT NOT NULL DEFAULT 0,
    archive_path TEXT,
    archive_sha256 CHAR(64),
    import_batch_id BIGINT REFERENCES import_batch(id),
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX sync_run_one_active_per_source ON sync_run(source_code)
    WHERE status IN ('QUEUED','FETCHING','ARCHIVING','IMPORTING');
CREATE INDEX sync_run_recent_idx ON sync_run(created_at DESC);

CREATE TABLE sync_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES sync_run(id),
    event_type TEXT NOT NULL,
    message TEXT NOT NULL,
    details JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX sync_event_run_idx ON sync_event(run_id,id);

