CREATE TABLE camera_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname VARCHAR(30) NOT NULL,
    content VARCHAR(2000) NOT NULL,
    screenshot_type VARCHAR(20) NOT NULL,
    screenshot_data BYTEA NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at TIMESTAMPTZ,
    reviewed_by TEXT,
    decision_reason VARCHAR(500),
    camera_id BIGINT REFERENCES camera(id),
    CONSTRAINT camera_report_status_check CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);
CREATE INDEX camera_report_status_page_idx ON camera_report(status, created_at DESC, id DESC);
CREATE UNIQUE INDEX camera_report_camera_idx ON camera_report(camera_id) WHERE camera_id IS NOT NULL;
